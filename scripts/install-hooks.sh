#!/usr/bin/env bash
# Install both git hooks. Run once per clone.
#
#   pre-commit  → pre-commit framework (ruff, mypy, bandit, sonar) ~5s
#   pre-push    → scripts/gate.sh (full suite, types, layers, coverage, Sonar) ~3min
#
# The pre-push hook is a two-line shim so the real gate stays version controlled;
# .git/hooks/ is not, and a gate that lives only in an untracked directory is one
# clone away from not existing.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

if command -v pre-commit >/dev/null 2>&1; then
  pre-commit install
else
  echo "warning: pre-commit not on PATH — the ~5s commit gate will not run." >&2
  echo "         pip install pre-commit && scripts/install-hooks.sh" >&2
fi

HOOK=".git/hooks/pre-push"
cat > "$HOOK" <<'EOF'
#!/usr/bin/env bash
# Generated by scripts/install-hooks.sh — edit scripts/gate.sh, not this file.
exec "$(git rev-parse --show-toplevel)/scripts/gate.sh"
EOF
chmod +x "$HOOK" scripts/gate.sh scripts/sonar-publish.sh

echo "installed: .git/hooks/pre-commit, .git/hooks/pre-push -> scripts/gate.sh"
